package aurbuild

import (
	"errors"
	"reflect"
	"strings"
	"testing"
)

const sampleSrcinfo = `# Generated by makepkg
pkgbase = multi
	pkgdesc = a split package
	pkgver = 2.1
	pkgrel = 3
	epoch = 1
	url = https://example.org/multi
	arch = x86_64
	makedepends = cmake
	checkdepends = check
	depends = glibc
	depends_x86_64 = libx>=2
	source = multi-2.1.tar.gz::https://example.org/multi-2.1.tar.gz
	source = fix.patch
	source_x86_64 = http://example.org/blob.bin
	sha256sums = abc
	sha256sums = SKIP
	b2sums = SKIP
	b2sums = SKIP
	sha256sums_x86_64 = SKIP

pkgname = multi
pkgname = multi-extra
	depends = multi
	depends = qt6-base
`

func TestParseSrcinfo(t *testing.T) {
	si, err := ParseSrcinfo(sampleSrcinfo)
	if err != nil {
		t.Fatal(err)
	}
	if si.Base != "multi" || si.Version != "1:2.1-3" || si.URL != "https://example.org/multi" {
		t.Fatalf("base %q version %q url %q", si.Base, si.Version, si.URL)
	}
	if !reflect.DeepEqual(si.Depends, []string{"glibc", "libx>=2"}) || !reflect.DeepEqual(si.Makedepends, []string{"cmake"}) || !reflect.DeepEqual(si.Checkdepends, []string{"check"}) {
		t.Fatalf("deps %v / %v / %v", si.Depends, si.Makedepends, si.Checkdepends)
	}
	// source 0 has a real sum in one algorithm, source 1 and the arch one are SKIP everywhere
	want := []Source{{"multi-2.1.tar.gz::https://example.org/multi-2.1.tar.gz", true}, {"fix.patch", false}, {"http://example.org/blob.bin", false}}
	if !reflect.DeepEqual(si.Sources, want) {
		t.Fatalf("sources = %+v", si.Sources)
	}
	if !reflect.DeepEqual(si.EffectiveDepends("multi"), si.Depends) {
		t.Fatalf("multi has no own depends: it takes the global list, got %v", si.EffectiveDepends("multi"))
	}
	if !reflect.DeepEqual(si.EffectiveDepends("multi-extra"), []string{"multi", "qt6-base"}) {
		t.Fatalf("multi-extra = %v", si.EffectiveDepends("multi-extra"))
	}
	if !si.HasPackage("multi-extra") || si.HasPackage("other") {
		t.Fatal("HasPackage")
	}
	for in, want := range map[string]string{"glibc>=2.38": "glibc", "foo": "foo", "bar=1": "bar", "tk: gui": "tk", "a<2": "a"} {
		if got := DepName(in); got != want {
			t.Errorf("DepName(%q) = %q, want %q", in, got, want)
		}
	}
}

func TestParseSrcinfoRefusals(t *testing.T) {
	for name, text := range map[string]string{
		"garbage line": "pkgbase = a\nthis is not key value\n",
		"no pkgname":   "pkgbase = a\n\tpkgver = 1\n",
		"no pkgver":    "pkgbase = a\n\npkgname = a\n",
		"no base":      "\tpkgver = 1\n\npkgname = a\n",
		"too big":      strings.Repeat("#\n", maxSrcinfo),
	} {
		if _, err := ParseSrcinfo(text); !errors.Is(err, ErrSrcinfo) {
			t.Errorf("%s: err = %v, want ErrSrcinfo", name, err)
		}
	}
	// epoch 0 is no epoch; no pkgrel is fine for the version text
	si, err := ParseSrcinfo("pkgbase = a\n\tpkgver = 1\n\tepoch = 0\n\npkgname = a\n")
	if err != nil || si.Version != "1" {
		t.Fatalf("version = %q, %v", si.Version, err)
	}
	if got := clip(strings.Repeat("x", 100)); len(got) != 63 {
		t.Fatalf("clip = %d", len(got))
	}
}
